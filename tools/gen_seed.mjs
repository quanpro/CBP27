#!/usr/bin/env node
// Generates backend/Seed.gs from docs/data/courses.json (public data only:
// course order and default dates, the self-rating scale, episode numbers and English
// titles, programme dates). No URLs, no item text, no names.
// Usage: node tools/gen_seed.mjs           # write backend/Seed.gs
//        node tools/gen_seed.mjs --check   # exit 1 if backend/Seed.gs is out of date
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(ROOT, 'docs', 'data', 'courses.json');
const OUT = join(ROOT, 'backend', 'Seed.gs');

export function buildSeed(data) {
  const p = data.program || {};
  const seed = {
    program: {
      baseline: { wave: p.baseline.wave, open_from: p.baseline.open_from, open_to: p.baseline.open_to },
      retest: p.retest ? { wave: p.retest.wave, open_from: p.retest.open_from, open_to: p.retest.open_to } : null,
      pitch_day: p.pitch_day || '',
      capstone_day: p.capstone_day || ''
    },
    scale: (data.scale || []).map((s) => ({ level: s.level, en: s.en, vi: s.vi, abbr: s.abbr || '', desc_en: s.desc_en, desc_vi: s.desc_vi })),
    courses: [],
    episodes: []
  };
  const courses = (data.courses || []).slice().sort((a, b) => (a.order || 99) - (b.order || 99));
  for (const c of courses) {
    seed.courses.push({
      code: c.code,
      order: c.order,
      cycle: c.cycle,
      online_from: c.online_from || '',
      checkpoint_close: c.checkpoint_close || '',
      forum_date: c.forum_date || '',
      field_until: c.field_until || '',
      objectives: (c.objectives || []).length
    });
    if (c.has_trailer) seed.episodes.push({ course: c.code, ep: 0, title_en: 'Trailer' });
    for (const e of c.episodes || []) seed.episodes.push({ course: c.code, ep: e.ep, title_en: e.title_en || '' });
  }
  return seed;
}

export function renderSeed(seed) {
  return [
    '/**',
    ' * Seed.gs · GENERATED by tools/gen_seed.mjs from docs/data/courses.json. Do not edit by hand:',
    ' * change courses.json and run `node tools/gen_seed.mjs`. Public data only (no URLs, no items).',
    ' * Used by setupSheet() for Courses order/date defaults, Episodes rows, Config defaults and',
    ' * the baseline Part A scale.',
    ' */',
    'var SEED = ' + JSON.stringify(seed, null, 2) + ';',
    ''
  ].join('\n');
}

function main() {
  const data = JSON.parse(readFileSync(SRC, 'utf8'));
  const text = renderSeed(buildSeed(data));
  if (process.argv.includes('--check')) {
    const cur = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
    if (cur !== text) { console.error('✖ backend/Seed.gs is out of date: run node tools/gen_seed.mjs'); process.exit(1); }
    console.log('✔ backend/Seed.gs is in sync with docs/data/courses.json');
    return;
  }
  writeFileSync(OUT, text);
  console.log(`✔ wrote backend/Seed.gs (${buildSeed(data).courses.length} courses, ${buildSeed(data).episodes.length} episodes)`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
